body = [
 "低视力读者在使用普通网页阅读长文时，最常见的困扰是放大字号后版面错乱、横向滚动条出现、以及重排后找不到刚才读到的位置。本工具的设计目标就是解决这三个问题。",
 "排版引擎把整篇文档切分为句子，每个句子都被赋予一个稳定的编号。无论字号如何变化，这个编号都不会改变，因此系统始终知道用户正在阅读的是哪一句话。",
 "当用户放大字号时，浏览器会自然地重新换行。此时系统并不重新猜测用户的位置，而是把之前记录的那一句话滚动回视口中原来的相对高度。因为锚点在整个调整过程中保持不变，所以结果只取决于最终的字号，不会因为中间经过多次微调而累积误差。",
 "栏宽同样可以调节。较窄的栏宽能减少眼球来回移动的距离，对部分低视力读者更友好。栏宽变化时，正文会自动重新分行，长单词和网址也会被强制折断，绝不会撑出版面产生横向滚动条。",
 "有些段落本身很长，在特大字号下一段可能占据好几个屏幕。由于正文采用普通的文档流排布，段落不会被裁切或重叠，用户只需自然滚动即可逐行读完。",
 "界面左侧的三角标记指示当前阅读位置，被标记的句子同时会以底色高亮。用户可以在调整字号前后对照这个标记，确认它仍然指向同一处内容。",
 "窗口尺寸变化也会触发同样的重排逻辑。无论是拖动窗口边缘，还是在不同显示器之间移动窗口，阅读位置都会稳定收敛到同一句话上，不会出现闪烁或跳回文首的情况。",
]
text = "易读 · 示例长文\n\n"
for i in range(1, 61):
    text += f"（第{i}节）" + body[i % len(body)] + "\n\n"
with open("sample.txt", "w", encoding="utf-8") as f:
    f.write(text)
print(len(text), "chars written")
